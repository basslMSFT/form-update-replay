import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Lists the licenses of everything that ends up in the shipped bundle (production dependencies only).
const cwd = "src/web-resources";
const paths = execSync("npm ls --omit=dev --all --parseable", { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  .split(/\r?\n/)
  .map((p) => p.trim())
  .filter((p) => p && existsSync(join(p, "package.json")));

const seen = new Map();
for (const p of paths) {
  const pkg = JSON.parse(readFileSync(join(p, "package.json"), "utf8"));
  if (!pkg.name || pkg.name === "form-update-replay-webresources") continue;
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (pkg.licenses?.map((l) => l.type).join(" OR ") ?? "UNKNOWN");
  seen.set(`${pkg.name}@${pkg.version}`, license);
}

const rows = [...seen.entries()].sort(([a], [b]) => a.localeCompare(b));
const byLicense = rows.reduce((m, [, l]) => m.set(l, (m.get(l) ?? 0) + 1), new Map());

const lines = [
  "# Third-party notices",
  "",
  "The web resources bundle the open-source packages below. Each package keeps its own license; the full license texts are in the package sources.",
  "This file is generated by `node scripts/generate-notices.mjs`.",
  "",
  "## Summary",
  "",
  ...[...byLicense.entries()].sort().map(([l, n]) => `- ${l}: ${n}`),
  "",
  "## Packages",
  "",
  "| Package | License |",
  "|---------|---------|",
  ...rows.map(([name, l]) => `| ${name} | ${l} |`),
  "",
];
writeFileSync("THIRD-PARTY-NOTICES.md", lines.join("\n"));
console.log(`${rows.length} packages`, Object.fromEntries(byLicense));

const allowed = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0)$/;
const bad = rows.filter(([, l]) => !allowed.test(l));
if (bad.length) { console.error("Review these licenses:", bad); process.exitCode = 1; }
