export const DICTIONARIES: Record<Lang, Record<StringKey, string>> = { en, nl };

/** Dutch (LCID 1043) switches to Dutch; every other language falls back to English. */
export function langFromLcid(lcid: number | undefined): Lang {
  return lcid === 1043 ? "nl" : "en";
}

let current: Lang = "en";

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: StringKey, ...args: Array<string | number>): string {
  const text = DICTIONARIES[current][key];
  return text.replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ""));
}
